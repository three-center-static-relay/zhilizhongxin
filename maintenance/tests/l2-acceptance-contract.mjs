import assert from "node:assert/strict";
import fs from "node:fs";
import {findVersionByTag,currentDeployment,stableVersion,stageSpecs,sameSnapshot} from "../scripts/run-l2-candidate-acceptance-core.mjs";
const gateSource=fs.readFileSync(new URL("../../scripts/cloudflare-worker-gate.mjs",import.meta.url),"utf8");
const wrapperSource=fs.readFileSync(new URL("../scripts/run-l2-candidate-acceptance.mjs",import.meta.url),"utf8");
const coreSource=fs.readFileSync(new URL("../scripts/run-l2-candidate-acceptance-core.mjs",import.meta.url),"utf8");
const trigger=JSON.parse(fs.readFileSync(new URL("../l2-acceptance-request.json",import.meta.url),"utf8"));
assert.match(gateSource,/if\(mode==="preview"\)return\["--yes",`wrangler@\$\{wranglerVersion\}`,"deploy","--dry-run"\]/);
assert.match(wrapperSource,/L2_MAINTENANCE_STAGE_RESTORE_PROBE_MODE/);
assert.match(wrapperSource,/remote_dev:false/);
assert.match(wrapperSource,/build_secret_value_read:false/);
assert.match(coreSource,/"versions","upload"/);
assert.match(coreSource,/"versions","deploy"/);
assert.match(coreSource,/"deployments","status"/);
assert.match(coreSource,/production_candidate_percentage:0/);
assert.match(coreSource,/restore_verified:true/);
assert.match(coreSource,/build_secret_value_read:false/);
assert.match(coreSource,/ai_gateway_called:false/);
assert.match(coreSource,/dynamic_routes_mutated:false/);
assert.doesNotMatch(coreSource,/wrangler@\$\{WRANGLER\}`,"dev"/);
assert.doesNotMatch(coreSource,/CLOUDFLARE_AI_GATEWAY_API_TOKEN/);
assert.equal(trigger.schema,"expert-l2-acceptance-v1");
assert.equal(trigger.enabled,true);
const a="11111111-1111-4111-8111-111111111111";
const b="22222222-2222-4222-8222-222222222222";
const old="33333333-3333-4333-8333-333333333333";
assert.equal(findVersionByTag([{id:a,tag:"abcdef123456"}],"abcdef123456"),a);
assert.throws(()=>findVersionByTag([{id:a,tag:"x"}],"abcdef123456"),/CANDIDATE_VERSION_TAG_MATCH/);
assert.deepEqual(currentDeployment({versions:[{version_id:old,percentage:100}]}),[{id:old,percentage:100}]);
