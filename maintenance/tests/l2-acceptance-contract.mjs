assert.equal(stableVersion([{id:old,percentage:100},{id:b,percentage:0}]),old);
assert.deepEqual(stageSpecs([{id:old,percentage:100}],a),[{id:old,percentage:100},{id:a,percentage:0}]);
assert.equal(sameSnapshot([{id:old,percentage:100},{id:b,percentage:0}],[{id:b,percentage:0},{id:old,percentage:100}]),true);
console.log(JSON.stringify({ok:true,suite:"l2-maintenance-stage-restore-probe-contract",maintenance_version_upload:true,maintenance_zero_percent_staging:true,deployment_restore_required:true,remote_dev_disabled:true,build_secret_value_read_disabled:true,ai_gateway_disabled:true,dynamic_route_mutation_disabled:true}));
